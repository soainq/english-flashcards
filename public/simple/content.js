  function categoryFor(lesson) {
    if (lesson.level.includes('UI/UX')) return 'UI/UX';
    if (lesson.level.includes('IELTS')) return 'IELTS';
    if (lesson.level.includes('CÔNG VIỆC') || lesson.level.includes('SỰ NGHIỆP')) return 'Công việc';
    return 'Đời sống';
  }

  const topics = source.map((lesson, day) => {
    const category = categoryFor(lesson);
    const words = lesson.words.map((word, index) => ({
      id: `${day}:${index}`,
      sourceDay: day,
      sourceIndex: index,
      category,
      topic: lesson.title,
      topicDescription: lesson.description,
      level: lesson.level,
      word: word.word,
      ipa: word.ipa,
      meaning: word.meaning,
      examples: [word.example, ...(extraExamples[word.word] || [])].slice(0, 3),
      exampleTranslations: [word.translation, ...(extraExampleTranslations[word.word] || [])].slice(0, 3),
      exampleAudioPaths: [
        `/audio/${day + 1}-${index + 1}-sentence.mp3`,
        `/audio/${day + 1}-${index + 1}-example-2.mp3`,
        `/audio/${day + 1}-${index + 1}-example-3.mp3`
      ],
      translation: word.translation
    }));
    return {
      id: `topic-${day}`,
      title: lesson.title,
      description: lesson.description,
      level: lesson.level,
      category,
      words
    };
  });

  const legacyAll = topics.flatMap((topic) => topic.words);
  const legacyByWord = new Map(legacyAll.map((item) => [item.word, item]));
  const curriculum = window.THEMED_CURRICULUM.map((topic) => {
    const rawDays = topic.days || topic.sourceDays.map(([title, wordNames]) => ({
      title,
      words: wordNames.map((word) => {
        const sourceWord = legacyByWord.get(word);
        if (!sourceWord) throw new Error(`Missing curriculum word: ${word}`);
        return sourceWord;
      })
    }));
    return {
      id: topic.id,
      title: topic.title,
      description: topic.description,
      category: topic.category,
      days: rawDays.map((day, dayIndex) => ({
        title: day.title,
        words: day.words.map((word) => ({
          ...word,
          category: topic.category,
          topic: topic.title,
          subtopic: day.title,
          introducedDay: dayIndex
        }))
      }))
    };
  });
  const curriculumAll = curriculum.flatMap((topic) => topic.days.flatMap((day) => day.words));
  const all = Array.from(new Map([...legacyAll, ...curriculumAll].map((item) => [item.id, item])).values());
  window.SIMPLE_CONTENT = {
    topics,
    curriculum,
    all,
    basic: all.filter((item) => item.category !== 'UI/UX'),
    uiux: all.filter((item) => item.category === 'UI/UX')
  };
